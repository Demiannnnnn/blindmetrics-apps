#!/usr/bin/env bash
# Sets up the orchestration environment on a PC (macOS or Linux, x86_64 or arm64): Docker engine,
# the agy-pro / agy-plus containers, host wrappers and the orchestration worktrees.
# Idempotent: on a configured PC it only checks. Run it as the owner (it may install software).
# Usage: tools/orchestration/agy-env/setup.sh                 (from any worktree of telemetry-apps)
#        WORKSPACE=/path/with/the/repos tools/orchestration/agy-env/setup.sh
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
ENV_DIR=${AGY_ENV_DIR:-$HOME/agy-multi}
BIN=$HOME/.local/bin
MAIN=$(dirname "$(git -C "$HERE" rev-parse --path-format=absolute --git-common-dir)")   # owner's checkout
WORKSPACE=${WORKSPACE:-$(dirname "$MAIN")}
say() { printf '\n==> %s\n' "$*"; }
die() { printf '\n✗ %s\n' "$*" >&2; exit 1; }

[ "$(id -u)" -ne 0 ] || die "Ejecuta como tu usuario normal, no como root."
command -v git >/dev/null || die "Falta git."

say "1/6 Motor Docker"
case "$(uname)" in
  Darwin)
    if ! docker info >/dev/null 2>&1; then
      command -v brew >/dev/null || die "Instala Homebrew primero: https://brew.sh"
      for f in docker docker-compose colima; do brew list --formula "$f" >/dev/null 2>&1 || brew install "$f"; done
      # docker compose plugin from Homebrew
      mkdir -p "$HOME/.docker"
      python3 - "$HOME/.docker/config.json" "$(brew --prefix)/lib/docker/cli-plugins" <<'EOF'
import json, os, sys
p, d = sys.argv[1], sys.argv[2]
c = json.load(open(p)) if os.path.exists(p) else {}
dirs = c.setdefault("cliPluginsExtraDirs", [])
if d not in dirs: dirs.append(d)
json.dump(c, open(p, "w"), indent=2)
EOF
      if colima list 2>/dev/null | grep -q '^default'; then
        colima start
      else
        ncpu=$(sysctl -n hw.ncpu); ram=$(( $(sysctl -n hw.memsize) / 1073741824 ))
        cpu=$(( ncpu / 2 < 2 ? 2 : ncpu / 2 )); mem=$(( ram * 3 / 4 )); mem=$(( mem > 12 ? 12 : mem < 4 ? 4 : mem ))
        colima start --cpu "$cpu" --memory "$mem" --disk 60 --vm-type vz --mount-type virtiofs
      fi
      brew services start colima >/dev/null 2>&1 || true   # start at login
    fi
    ;;
  Linux)
    if ! command -v docker >/dev/null || ! docker compose version >/dev/null 2>&1; then
      die "Falta Docker Engine con el plugin compose. Instálalo (requiere sudo) y vuelve a ejecutar:
  Arch/CachyOS:  sudo pacman -S --needed docker docker-compose docker-buildx
  Debian/Ubuntu: curl -fsSL https://get.docker.com | sudo sh
  Fedora:        sudo dnf install docker-ce docker-ce-cli containerd.io docker-compose-plugin  (repo de Docker)
luego: sudo systemctl enable --now docker && sudo usermod -aG docker \$USER  (y cierra sesión / vuelve a entrar)"
    fi
    docker info >/dev/null 2>&1 || die "Docker está instalado pero no responde. Revisa: sudo systemctl enable --now docker; que tu usuario esté en el grupo docker (id -nG) y que hayas vuelto a iniciar sesión."
    ;;
  *) die "Sistema no soportado: $(uname). En Windows usa WSL2 (Ubuntu) y ejecuta este script dentro." ;;
esac
docker compose version >/dev/null 2>&1 || die "docker compose no está disponible."
echo "Docker OK ($(docker version --format '{{.Server.Version}}' 2>/dev/null))"

say "2/6 Archivos del entorno en $ENV_DIR (WORKSPACE=$WORKSPACE)"
mkdir -p "$ENV_DIR"
cp "$HERE/Dockerfile" "$HERE/compose.yml" "$HERE/agy-in" "$HERE/agy-login" "$ENV_DIR/"
chmod +x "$ENV_DIR/agy-in" "$ENV_DIR/agy-login"
printf 'WORKSPACE=%s\nAGY_UID=%s\n' "$WORKSPACE" "$(id -u)" > "$ENV_DIR/.env"

say "3/6 Imagen y contenedores agy-pro / agy-plus"
docker compose -f "$ENV_DIR/compose.yml" up -d --build

say "4/6 Comandos en $BIN"
mkdir -p "$BIN"
for a in pro plus; do printf '#!/usr/bin/env bash\nexec "%s/agy-in" %s "$@"\n' "$ENV_DIR" "$a" > "$BIN/agy-$a"; chmod +x "$BIN/agy-$a"; done
ln -sf "$ENV_DIR/agy-login" "$BIN/agy-login"
case ":$PATH:" in *":$BIN:"*) ;; *) echo "⚠ Agrega $BIN a tu PATH para usar agy-pro, agy-plus y agy-login." ;; esac

say "5/6 Worktrees de orquestación en $WORKSPACE"
git -C "$MAIN" fetch -q origin || echo "⚠ git fetch falló; uso lo que hay en local."
git -C "$MAIN" show-ref --verify --quiet refs/heads/develop-AGENTS \
  || git -C "$MAIN" branch -q --track develop-AGENTS origin/develop-AGENTS
for wt in orch pro plus; do
  d="$WORKSPACE/ta-wt-$wt"
  if [ -e "$d" ]; then echo "ta-wt-$wt ya existe"; continue; fi
  if [ "$wt" = orch ]; then git -C "$MAIN" worktree add -q "$d" develop-AGENTS
  else git -C "$MAIN" worktree add -q --detach "$d" develop-AGENTS; fi
  echo "ta-wt-$wt creado"
done
# Sessions opened in WORKSPACE (or in the owner's checkout on main) would not see develop-AGENTS' CLAUDE.md
if [ ! -e "$WORKSPACE/CLAUDE.md" ]; then
  cat > "$WORKSPACE/CLAUDE.md" <<EOF
# Workspace (generated by telemetry-apps/tools/orchestration/agy-env/setup.sh)

Claude is the **orchestrator** in these repos: agy implements (two Google accounts, Docker containers
agy-pro / agy-plus), Claude designs, launches agy, reviews, tests and merges — never writes product code.
Before any work read \`ta-wt-orch/CLAUDE.md\` and \`ta-wt-orch/tools/orchestration/README.md\`
(branch develop-AGENTS of telemetry-apps). The owner's checkouts are on \`main\`, where those docs are empty.
EOF
  echo "CLAUDE.md de arranque creado en $WORKSPACE"
fi
[ -n "$(git -C "$MAIN" config user.email || true)" ] \
  || echo "⚠ El repo no tiene identidad de git: git -C $MAIN config user.name '…'; git -C $MAIN config user.email '…'"

say "6/6 Verificación"
docker exec agy-pro bash -c 'cargo --version && node --version && agy --version' | sed 's/^/  /'
pending=""
for a in pro plus; do
  if docker exec "agy-$a" timeout 90 agy -p "responde solo: ok" --print-timeout 60s 2>/dev/null | grep -qi ok; then
    echo "✓ agy-$a autenticado"
  else
    echo "✗ agy-$a sin login"; pending="$pending $a"
  fi
done
if [ -n "$pending" ]; then
  echo
  echo "Falta el login de Google (necesita navegador; hazlo en una terminal normal):"
  for a in $pending; do echo "  agy-login $a    # cuenta Google AI $(echo "$a" | tr '[:lower:]' '[:upper:]')"; done
  exit 4
fi
echo
echo "Entorno listo. Siguiente: tools/orchestration/usage.sh"
